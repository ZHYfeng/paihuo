// Command gen-types generates the frontend DTOs that mirror selected Store structs.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

const (
	storeModelsPath = "internal/store/models.go"
	generatedPath   = "frontend/src/generated/store-types.ts"
)

var storeTargets = []string{"RoleConfig", "Role", "Task", "Project"}

var storeOverrides = map[string]string{
	"Role.DelegationMaxPerm": "TaskPerm",
	"Task.Type":              "TaskType",
	"Task.Perm":              "TaskPerm",
	"Task.RunMode":           "TaskRunMode",
	"Task.DependencyMode":    "TaskDependencyMode",
	"Task.DependsOn":         "ID | null",
	"Task.ResumeOf":          "ID | null",
	"Task.MergeOf":           "ID | null",
	"Project.Status":         "ProjectStatus",
}

const generatedPrelude = `// Code generated by go run ./scripts/gen-types.go; DO NOT EDIT.

export type ID = number;
export type TaskType = "task" | "session" | "workflow";
export type TaskPerm = "full" | "review";
export type TaskRunMode = "batch" | "interactive";
export type TaskDependencyMode = "none" | "weak" | "strong";
export type ProjectStatus = "active" | "archived";
`

func main() {
	check := flag.Bool("check", false, "check generated output without writing it")
	flag.Parse()

	source, err := os.ReadFile(storeModelsPath)
	if err != nil {
		fatal(err)
	}
	output, err := generateTypes(source, storeTargets, storeOverrides, generatedPrelude)
	if err != nil {
		fatal(err)
	}
	if *check {
		current, err := os.ReadFile(generatedPath)
		if err != nil {
			fatal(fmt.Errorf("read generated DTOs: %w", err))
		}
		if !bytes.Equal(current, output) {
			fatal(fmt.Errorf("%s is out of date; run go run ./scripts/gen-types.go", generatedPath))
		}
		return
	}
	if err := os.MkdirAll("frontend/src/generated", 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(generatedPath, output, 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen-types:", err)
	os.Exit(1)
}

func generateTypes(source []byte, targets []string, overrides map[string]string, prelude string) ([]byte, error) {
	file, err := parser.ParseFile(token.NewFileSet(), storeModelsPath, source, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse Store models: %w", err)
	}
	structs := make(map[string]*ast.StructType)
	for _, declaration := range file.Decls {
		gen, ok := declaration.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, item := range gen.Specs {
			typeSpec, ok := item.(*ast.TypeSpec)
			if !ok {
				continue
			}
			if structType, ok := typeSpec.Type.(*ast.StructType); ok {
				structs[typeSpec.Name.Name] = structType
			}
		}
	}

	var output strings.Builder
	output.WriteString(strings.TrimRight(prelude, "\n"))
	output.WriteString("\n\n")
	for index, name := range targets {
		structType, ok := structs[name]
		if !ok {
			return nil, fmt.Errorf("Store struct %s not found", name)
		}
		if err := writeInterface(&output, name, structType, structs, overrides, ""); err != nil {
			return nil, err
		}
		if index < len(targets)-1 {
			output.WriteByte('\n')
		}
	}
	return []byte(output.String()), nil
}

func writeInterface(output *strings.Builder, structName string, structType *ast.StructType, structs map[string]*ast.StructType, overrides map[string]string, indent string) error {
	if indent == "" {
		fmt.Fprintf(output, "export interface %s {\n", structName)
	} else {
		output.WriteString("{\n")
	}
	for _, field := range structType.Fields.List {
		if len(field.Names) == 0 {
			return fmt.Errorf("%s: embedded fields are unsupported", structName)
		}
		jsonName, optional, skip, err := jsonField(field)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", structName, field.Names[0].Name, err)
		}
		if skip {
			continue
		}
		for _, name := range field.Names {
			fieldName := jsonName
			if len(field.Names) > 1 || fieldName == "" {
				fieldName = name.Name
			}
			path := structName + "." + name.Name
			typeName, err := typescriptType(field.Type, path, name.Name, structs, overrides, indent+"  ")
			if err != nil {
				return err
			}
			fmt.Fprintf(output, "%s  %s%s: %s;\n", indent, fieldName, map[bool]string{true: "?", false: ""}[optional], typeName)
		}
	}
	fmt.Fprintf(output, "%s}\n", indent)
	return nil
}

func jsonField(field *ast.Field) (name string, optional, skip bool, err error) {
	if field.Tag == nil {
		return "", false, false, nil
	}
	tag, err := strconv.Unquote(field.Tag.Value)
	if err != nil {
		return "", false, false, fmt.Errorf("invalid struct tag: %w", err)
	}
	jsonTag := reflect.StructTag(tag).Get("json")
	if jsonTag == "" {
		return "", false, false, nil
	}
	parts := strings.Split(jsonTag, ",")
	if parts[0] == "-" {
		return "", false, true, nil
	}
	for _, option := range parts[1:] {
		if option == "omitempty" {
			optional = true
		}
	}
	return parts[0], optional, false, nil
}

func typescriptType(expression ast.Expr, path, fieldName string, structs map[string]*ast.StructType, overrides map[string]string, indent string) (string, error) {
	if override, ok := overrides[path]; ok {
		return override, nil
	}
	switch value := expression.(type) {
	case *ast.Ident:
		if isIDField(fieldName) && isIntegerType(value.Name) {
			return "ID", nil
		}
		switch value.Name {
		case "string":
			return "string", nil
		case "bool":
			return "boolean", nil
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "float32", "float64":
			return "number", nil
		}
		if _, ok := structs[value.Name]; ok {
			return value.Name, nil
		}
		return "", unsupported(path, value.Name)
	case *ast.StarExpr:
		mapped, err := typescriptType(value.X, path, fieldName, structs, overrides, indent)
		if err != nil {
			return "", err
		}
		return addNull(mapped), nil
	case *ast.ArrayType:
		mapped, err := typescriptType(value.Elt, path, "", structs, overrides, indent)
		if err != nil {
			return "", err
		}
		array := "Array<" + mapped + ">"
		if value.Len == nil {
			return addNull(array), nil
		}
		return array, nil
	case *ast.MapType:
		key, ok := value.Key.(*ast.Ident)
		if !ok || key.Name != "string" {
			return "", unsupported(path, "map key")
		}
		mapped, err := typescriptType(value.Value, path, "", structs, overrides, indent)
		if err != nil {
			return "", err
		}
		return addNull("Record<string, " + mapped + ">"), nil
	case *ast.StructType:
		var nested strings.Builder
		if err := writeInterface(&nested, path, value, structs, overrides, indent); err != nil {
			return "", err
		}
		return strings.TrimSpace(nested.String()), nil
	default:
		return "", unsupported(path, fmt.Sprintf("%T", expression))
	}
}

func isIntegerType(name string) bool {
	switch name {
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64":
		return true
	default:
		return false
	}
}

func isIDField(name string) bool {
	return name == "ID" || strings.HasSuffix(name, "ID")
}

func addNull(typeName string) string {
	parts := strings.Split(typeName, " | ")
	for _, part := range parts {
		if part == "null" {
			return typeName
		}
	}
	parts = append(parts, "null")
	sort.Strings(parts)
	for index, part := range parts {
		if part == "null" {
			parts = append(parts[:index], parts[index+1:]...)
			parts = append(parts, "null")
			break
		}
	}
	return strings.Join(parts, " | ")
}

func unsupported(path, typeName string) error {
	return fmt.Errorf("%s: unsupported Go type %s", path, typeName)
}
